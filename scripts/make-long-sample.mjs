const TRANSITIONS = ["CUT TO:", "DISSOLVE TO:", "SMASH CUT TO:", "MATCH CUT TO:"];

function sceneBlock(index) {
  const [io, place] = pick(PLACES);
  const heading = place.startsWith("INT.") ? `${place} - ${pick(["DAY", "NIGHT"])}` : `${io}. ${place} - ${pick(TIMES)}`;
  const out = [`.${heading} #${index}#`, ""];

  const actionCount = 1 + Math.floor(rand() * 3);
  const actions = Array.from({ length: actionCount }, () => pick(ACTIONS));
  // 액션 줄 일부는 이어 쓰기 (빈 줄 없이)
  out.push(actions.join(chance(0.5) ? "\n" : "\n\n"), "");

  const cast = [pick(CHARACTERS), pick(CHARACTERS)];
  const exchanges = 3 + Math.floor(rand() * 6);
  for (let i = 0; i < exchanges; i++) {
    const who = cast[i % 2];
    out.push(`@${who}${pick(EXTENSIONS)}`);
    if (chance(0.3)) out.push(pick(PARENTHETICALS));
    out.push(pick(LINES[who]));
    if (chance(0.25)) out.push(pick(LINES[who]));
    out.push("");
    if (chance(0.35)) out.push(pick(ACTIONS), "");
  }

  // 가끔 긴 독백 (페이지를 넘어가는 대사 시험용)
  if (chance(0.12)) {
    out.push("@민재", "(오래 망설이다)", ...MONOLOGUE, ...MONOLOGUE.slice(0, 2), "");
  }

  if (chance(0.4)) out.push(`> ${pick(TRANSITIONS)}`, "");
  return out.join("\n");
}

